// Single source of truth for numbers and claims that appear in more than one place
// (README, website, tests): version, bundle sizes, browser support.
import { readFileSync } from 'node:fs';
import { gzipSync, brotliCompressSync, constants } from 'node:zlib';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const kb = (n) => (n / 1024).toFixed(1);

export function sizes() {
  const m = (f) => {
    const b = readFileSync(join(root, 'dist', f));
    return {
      raw: kb(b.length),
      gz: kb(gzipSync(b, { level: 9 }).length), // gzip -9, what `gzip -9 file | wc -c` reports
      br: kb(brotliCompressSync(b, { params: { [constants.BROTLI_PARAM_QUALITY]: 11 } }).length),
    };
  };
  return { full: m('mozert.min.js'), core: m('mozert.core.min.js'), css: m('mozert.min.css'), theme: m('mozert-theme.min.css'), jq: m('mozert.jquery.min.js') };
}

export const version = () => JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;

// Minimum versions come from the platform features the code needs: ES2015 syntax, ResizeObserver (optional, guarded),
// matchMedia, pointer/touch events, CSS flexbox + transforms, and aspect-ratio / gap for the thumbnail gallery.
export const SUPPORT = [
  ['Chrome, Edge, Opera (desktop)', '88+', 'Tested automatically (Chromium)'],
  ['Chrome for Android', '88+', 'Tested automatically (Chromium, phone emulation)'],
  ['Firefox (desktop and Android)', '89+', 'Test job in CI (Playwright Firefox)'],
  ['Safari (macOS)', '15+', 'Test job in CI (Playwright WebKit)'],
  ['Safari on iPhone and iPad', '15+', 'Test job in CI (Playwright WebKit, phone emulation)'],
  ['Samsung Internet', '15+', 'Same engine as Chrome, not tested separately'],
  ['Internet Explorer', 'Not supported', '-'],
];

export const supportMarkdown = () => ['| Browser | Minimum version | How it is checked |', '| --- | --- | --- |', ...SUPPORT.map((r) => `| ${r.join(' | ')} |`)].join('\n');

export function factsMarkdown() {
  const s = sizes();
  return `Version **${version()}** (this README is regenerated by \`npm run build\`, so it always matches the release).

| File | Minified | Gzip | Brotli |
| --- | --- | --- | --- |
| \`mozert.min.js\` (core + every effect and module) | ${s.full.raw} KB | **${s.full.gz} KB** | ${s.full.br} KB |
| \`mozert.core.min.js\` (core only, no effect modules) | ${s.core.raw} KB | **${s.core.gz} KB** | ${s.core.br} KB |
| \`mozert.min.css\` (layout) | ${s.css.raw} KB | ${s.css.gz} KB | ${s.css.br} KB |
| \`mozert-theme.min.css\` (optional theme) | ${s.theme.raw} KB | ${s.theme.gz} KB | ${s.theme.br} KB |
| \`mozert.jquery.min.js\` (optional adapter) | ${s.jq.raw} KB | ${s.jq.gz} KB | ${s.jq.br} KB |

Measured on the files in \`dist/\` after \`npm run build\` (\`gzip -9\`, Brotli quality 11). Use the core-only file when you need just the slider; the full file adds 3D effects, free mode, virtual slides, parallax, zoom, lightbox, thumbs, magnifier, scroll-driven mode and the rest.

### Browser support

${supportMarkdown()}`;
}
